using System.Buffers.Binary;
using System.IO;
using System.Text;

namespace InstallScriptGenerator.Core;

/// <summary>Packages a PowerShell installation script inside a self-contained Windows launcher.</summary>
public static class ExeExporter
{
    public const string Marker = "ISG2CFG!";

    public static async Task WriteAsync(
        string launcherTemplate, string destination,
        IReadOnlyList<InstallerFile> files, ScriptOptions options,
        CancellationToken cancellationToken = default)
    {
        if (!File.Exists(launcherTemplate))
            throw new FileNotFoundException(
                "Launcher template is missing. Use the Windows artifact generated by GitHub Actions.",
                launcherTemplate);

        string tempScript = Path.Combine(Path.GetTempPath(),
            "isg-build-" + Guid.NewGuid().ToString("N") + ".ps1");
        string tempOutput = destination + ".partial";
        try
        {
            // The script resolves all relative paths against the exported EXE's folder.
            await ScriptGenerator.WriteAsync(tempScript, files,
                options with { Format = ExportFormat.PowerShell }, cancellationToken,
                pathForRelatives: destination, launcherRoot: true);

            var length = new FileInfo(tempScript).Length;
            await using (var output = new FileStream(tempOutput, FileMode.Create,
                FileAccess.Write, FileShare.None, 65536, useAsync: true))
            {
                await using (var source = File.OpenRead(launcherTemplate))
                    await source.CopyToAsync(output, cancellationToken);
                await using (var script = File.OpenRead(tempScript))
                    await script.CopyToAsync(output, cancellationToken);

                byte[] size = new byte[8];
                BinaryPrimitives.WriteInt64LittleEndian(size, length);
                await output.WriteAsync(size, cancellationToken);
                await output.WriteAsync(Encoding.ASCII.GetBytes(Marker), cancellationToken);
                await output.FlushAsync(cancellationToken);
            }
            File.Move(tempOutput, destination, overwrite: true);
        }
        finally
        {
            if (File.Exists(tempOutput)) File.Delete(tempOutput);
            if (File.Exists(tempScript)) File.Delete(tempScript);
        }
    }
}
